export function t(key, vars) {
  let s = dictionaries[current][key] ?? ro[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  return s;
}
export const has = (key) => key in dictionaries[current] || key in ro;

