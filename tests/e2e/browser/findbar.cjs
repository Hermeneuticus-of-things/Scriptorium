// Scenario 7: Find bar — next/previous, replace, replace all with regex specials and diacritics, Escape.
const { open, ed, caretEnd, check, done } = require('./_helpers.cjs');
(async () => {
  const { browser, page, errors } = await open();
  const text = () => page.evaluate(() => document.querySelector('.pane .ProseMirror').editor.state.doc.textContent);
  const sel = () => page.evaluate(() => { const s = document.querySelector('.pane .ProseMirror').editor.state.selection; return [s.from, s.to]; });
  await caretEnd(page);
  await page.keyboard.press('Enter');
  await page.keyboard.type('Preț (a+b)? Preț (a+b)? ușă ȘI ușă.', { delay: 5 });
  await page.keyboard.press('Control+f');
  const q = page.locator('.find-bar input').first();
  const r = page.locator('.find-bar input').nth(1);
  check('find bar focused', await q.evaluate((el) => el === document.activeElement));
  await q.fill('(a+b)?');
  check('count with regex specials', (await page.locator('.find-bar .count').innerText()) === '1/2', await page.locator('.find-bar .count').innerText());
  await q.press('Enter'); const s1 = await sel();
  await q.press('Enter'); const s2 = await sel();
  await q.press('Shift+Enter'); const s3 = await sel();
  check('next moves forward', s2[0] > s1[0], `${s1} ${s2}`);
  check('previous moves back', s3[0] === s1[0], `${s3}`);
  await r.fill('$5');
  await page.locator('.find-bar button', { hasText: 'Înlocuiește' }).click();
  await page.waitForTimeout(50);
  check('literal $5 replacement in non-regex mode', (await text()).includes('Preț $5 Preț (a+b)?'), await text());
  // regex mode: groups expand
  await page.locator('.find-bar button[title="Expresie regulată"]').click();
  await q.fill('(Preț) \\$(\\d)');
  await r.fill('$2 $1');
  await page.locator('.find-bar button', { hasText: 'Toate' }).click();
  await page.waitForTimeout(50);
  check('regex groups expand', (await text()).includes('5 Preț Preț (a+b)?'), await text());
  await page.locator('.find-bar button[title="Expresie regulată"]').click();
  await q.fill('UȘĂ');
  check('case-insensitive diacritics', (await page.locator('.find-bar .count').innerText()) === '1/2');
  await r.fill('poartă');
  await page.locator('.find-bar button', { hasText: 'Toate' }).click();
  await page.waitForTimeout(50);
  check('replace all diacritics', (await text()).includes('poartă ȘI poartă.'), await text());
  await q.focus();
  await page.keyboard.press('Escape');
  await page.waitForTimeout(50);
  check('Escape closes', (await page.locator('.find-bar').count()) === 0);
  check('focus back in editor', await page.evaluate(() => document.activeElement.classList.contains('ProseMirror')));
  await page.keyboard.press('Control+z');
  check('undo replace-all in one step', (await text()).includes('5 Preț Preț (a+b)? ușă ȘI ușă.'), await text());
  check('no console errors', errors.length === 0, errors.join(' | '));
  await browser.close();
  done();
})();
